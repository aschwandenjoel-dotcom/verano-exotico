/** Findet die CJ-vid für eine bestellte Variante. Gibt null zurück wenn nicht gemappt. */
export function resolveVid(slug: string, colorName?: string, size?: string): string | null {
  const map = cjProductMap[slug];
  if (!map) return null;
  const v = map.variants ?? {};

  const candidates = [
    colorName && size ? `${colorName}|${size}` : null,
    colorName ?? null,
    size ? `|${size}` : null,
  ].filter(Boolean) as string[];

  for (const key of candidates) {
    if (v[key]) return v[key];
  }
  return map.defaultVid ?? null;
}
